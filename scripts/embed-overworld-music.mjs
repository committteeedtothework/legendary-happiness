// Reproducibly regenerate both offline catalogs from the original MP3 assets.
// Stream one recording at a time, and replace the generated module atomically.
import { readFile, rename, unlink } from "node:fs/promises";
import { createWriteStream } from "node:fs";
import { once } from "node:events";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/overworld-music-data.js"),
  temporary = target + `.${process.pid}.tmp`;
const stream = createWriteStream(temporary);
let failure;
stream.on("error", (error) => (failure = error));
async function write(text) {
  if (failure) throw failure;
  if (!stream.write(text)) await once(stream, "drain");
}
try {
  await write(
    "// Generated by scripts/embed-overworld-music.mjs; unchanged user-supplied recordings.\n",
  );
  for (const [folder, exportName] of [
    ["overworld", "OVERWORLD_TRACKS"],
    ["creative", "CREATIVE_TRACKS"],
  ]) {
    const base = resolve(root, "public/audio", folder),
      manifest = JSON.parse(
        await readFile(resolve(base, "manifest.json"), "utf8"),
      );
    await write(`export const ${exportName} = [`);
    for (let i = 0; i < manifest.tracks.length; i++) {
      const track = manifest.tracks[i],
        bytes = await readFile(resolve(base, track.file));
      if (createHash("sha256").update(bytes).digest("hex") !== track.sha256)
        throw Error(`MP3 hash mismatch: ${folder}/${track.file}`);
      const metadata = JSON.stringify(track);
      await write(
        (i ? "," : "") +
          metadata.slice(0, -1) +
          ',"src":"data:audio/mpeg;base64,',
      );
      await write(bytes.toString("base64"));
      await write('"}');
    }
    await write("];\n");
    console.log(
      `Embedded ${manifest.tracks.length} unchanged ${folder} recordings`,
    );
  }
  stream.end();
  await once(stream, "finish");
  if (failure) throw failure;
  await rename(temporary, target);
} catch (error) {
  stream.destroy();
  await unlink(temporary).catch(() => {});
  throw error;
}
